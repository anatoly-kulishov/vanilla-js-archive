/**
 * Объекты в JS: передача в функцию.
 *
 * Важно понимать разницу:
 * 1) Мутация свойства (o.a = 5) — меняет ТОТ ЖЕ объект в памяти.
 *    Снаружи это видно.
 * 2) Переприсваивание параметра (o = { ... }) — меняет только
 *    локальную переменную o внутри функции.
 *    Снаружи исходная переменная по-прежнему смотрит на старый объект.
 *
 * Говорят "объекты передаются по ссылке", точнее:
 * в функцию копируется ССЫЛКА (значение ссылки), а не сам объект.
 * Переписать эту копию ссылки ≠ переписать исходную переменную.
 */

// --- 1. Мутация: меняем свойство по той же ссылке ---
var obj1 = { a: 1 };

function mutate(o) {
    // При вызове mutate(obj1) в параметр o копируется ссылка на тот же объект.
    // o и obj1 — разные переменные, но обе указывают на ОДИН объект { a: 1 }.
    // Меняем свойство объекта → изменение видно и через obj1.
    o.a = 5;
}

mutate(obj1);
console.log(obj1); // { a: 5 } — исходный объект изменился

// --- 2. Переприсваивание: параметр теперь смотрит на другой объект ---
var obj2 = { a: 1 };

function reassign(o) {
    // Сначала o указывал на тот же объект, что и obj2.
    // Потом мы пишем o = { hello: 1 } — это НОВЫЙ объект.
    // Переменная o теперь смотрит на него.
    // Переменная obj2 снаружи по-прежнему смотрит на старый { a: 1 }.
    // Мы не меняли свойства старого объекта — только "перенаправили" локальный o.
    o = { hello: 1 };
}

reassign(obj2);
console.log(obj2); // { a: 1 } — без изменений

// --- 3. То же самое, даже если у нового объекта похожие ключи ---
var obj3 = { a: 1 };

function reassignSameShape(o) {
    // Легко перепутать с мутацией: ключ тоже называется a, значение 5.
    // Но это всё равно СОЗДАНИЕ нового объекта, а не правка старого.
    // Эквивалентно примеру 2, просто форма объекта похожа.
    o = { a: 5 };
}

reassignSameShape(obj3);
console.log(obj3); // { a: 1 } — снова без изменений
