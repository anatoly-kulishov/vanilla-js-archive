/**
 * Написать функцию, которая принимает на вход URL.
 * Асинхронно получает данные по этому URL в формате JSON
 * и возвращает их. Для получения данных использовать fetch.
 * Использовать только Promise API (без async/await).
 * При ошибке запроса повторить запрос ещё до 5 раз.
 * Если после всех попыток данные получить не удалось —
 * вернуть ошибку "Заданный URL недоступен".
 *
 * Схема попыток:
 *   попытка 1 → ошибка
 *   попытка 2 → ошибка
 *   ...
 *   попытка 6 → ошибка → reject("Заданный URL недоступен")
 *
 * То есть: 1 первая + до 5 дополнительных = максимум 6 запросов.
 */

function get(url) {
    const totalAttempts = 6;

    // tryFetch — одна попытка запроса.
    // attemptsLeft говорит, сколько попыток ещё осталось ВКЛЮЧАЯ текущую.
    // Если текущая упала и attemptsLeft стало 1 (это была последняя) —
    // больше не повторяем, отдаём ошибку.
    const tryFetch = (attemptsLeft) => {
        return fetch(url)
            .then((response) => {
                // fetch НЕ считает 404/500 ошибкой сам по себе —
                // промис resolve'ится, но response.ok === false.
                // Мы сами превращаем это в ошибку, чтобы сработал .catch
                // и пошла логика ретрая.
                if (!response.ok) {
                    throw new Error(response.statusText);
                }

                // Тело ответа читаем как JSON и отдаём дальше по цепочке
                return response.json();
            })
            .catch(() => {
                // Сюда попадаем при:
                // - сетевой ошибке
                // - !response.ok (мы сами throw выше)
                // - ошибке парсинга JSON (например, пришла HTML-страница)

                // Попытки кончились — фиксированная ошибка из условия задачи
                if (attemptsLeft <= 1) {
                    return Promise.reject("Заданный URL недоступен");
                }

                // Ещё есть запас: вызываем себя снова с attemptsLeft - 1.
                // Это рекурсия через промисы, не через стек вызовов сразу,
                // поэтому "переполнения стека" от большого числа попыток не будет.
                return tryFetch(attemptsLeft - 1);
            });
    };

    // Стартуем с полного запаса попыток и возвращаем промис наружу
    return tryFetch(totalAttempts);
}

// Для проверки нужен URL, который отдаёт именно JSON.
const url = "https://jsonplaceholder.typicode.com/todos/2";

get(url)
    .then((data) => console.log(data))
    .catch((error) => console.error(error));
