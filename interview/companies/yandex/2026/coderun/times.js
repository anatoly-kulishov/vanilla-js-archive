/**
 * Реализовать метод times для числового объекта.
 * Функция должна принимать callback и вызывать его
 * заданное количество раз с индексом текущей итерации.
 *
 * Пример: (3).times(console.log) выведет:
 *   0
 *   1
 *   2
 *
 * То есть callback вызывается N раз, и каждый раз получает
 * номер текущей итерации начиная с нуля.
 */

// Добавляем метод прямо в прототип Number,
// чтобы он появился у всех чисел: 3, (5), new Number(2) и т.д.
Number.prototype.times = function (callback) {
    // this внутри метода — то число, у которого вызвали .times
    // Например при (3).times(...) this — это объект-обёртка числа 3.
    // valueOf() достаёт обычное примитивное число 3.   `
    const timesCount = this.valueOf();

    // Обычный цикл от 0 до timesCount - 1.
    // На каждом шаге вызываем переданный callback с текущим index.*
    for (let i = 0; i < timesCount; i++) {
        callback(i);
    }
};

// Примеры
console.clear();
(3).times(console.log);
// 0
// 1
// 2
